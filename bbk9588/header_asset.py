"""Compile the original GPT Image PNG into the native header's RGB565 data.

Uses only the pinned SDK's PNG decoder/resampler. The source PNG is preserved;
transparent padding is excluded when fitting it into the 24-pixel header slot.
"""
from pathlib import Path
import hashlib
import sys

HERE = Path(__file__).resolve().parent

def compile_header(sdk):
    sys.path.insert(0, str(sdk))
    from bda_packer.vx_icon import read_png, resize_cover, rgb565_bytes
    source = HERE / 'assets/header-logo.png'
    sw, sh, pixels = read_png(source)
    left, top, right, bottom = sw, sh, -1, -1
    for index, pixel in enumerate(pixels):
        if pixel[3] > 8:
            x, y = index % sw, index // sw
            left, top = min(left, x), min(top, y)
            right, bottom = max(right, x), max(bottom, y)
    if right < left:
        raise ValueError('Header logo has no visible pixels')
    cw, ch = right-left+1, bottom-top+1
    content = [pixel for y in range(top,bottom+1)
               for pixel in pixels[y*sw+left:y*sw+right+1]]
    height = 24
    width = round(cw * height / ch)
    if not 1 <= width <= 150:
        raise ValueError('Header logo must fit before the audio status')
    data = rgb565_bytes(resize_cover(cw,ch,content,width,height),(17,26,36))
    words = [int.from_bytes(data[i:i+2],'little') for i in range(0,len(data),2)]
    lines = ['/* Generated by header_asset.py; original PNG remains unchanged. */',
             f'#define NPE_HEADER_WIDTH {width}',
             f'#define NPE_HEADER_HEIGHT {height}',
             'static const Uint16 npe_header_pixels[] = {']
    lines += ['    '+','.join(f'0x{word:04x}' for word in words[i:i+16])+','
              for i in range(0,len(words),16)]
    lines += ['};','']
    (HERE/'assets/header_rgb565.h').write_bytes('\n'.join(lines).encode('ascii'))
    return {'header_source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
            'header_pixels_sha256':hashlib.sha256(data).hexdigest(),
            'header_size':[width,height]}

if __name__ == '__main__':
    import json
    print(json.dumps(compile_header(HERE.parent/'sdk'),indent=2))
