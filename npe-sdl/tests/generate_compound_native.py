import json
from pathlib import Path

# References are exported from the unmodified original runtime executing
# independent RAM/resident-NPE fixtures, never computed with the C service.
samples = [json.loads(p.read_text()) for p in sorted(Path('tmp').glob('native-compound-*.json'))]
lines = ['/* Generated by npe-sdl/tests/generate_compound_native.py from original runtime samples. */',
         '#ifndef COMPOUND_NATIVE_H', '#define COMPOUND_NATIVE_H',
         'typedef struct { uint16_t hp, qi, base_attack, base_defense, attack, defense, attack_timer, defense_timer; } CompoundRecord;',
         'typedef struct { const char *name; unsigned id, item, side, group, type, enemies, rounds, refresh; uint16_t effects[4], refresh_effects[4]; unsigned refresh_changes; } CompoundCase;',
         'typedef struct { unsigned scenario, phase, inventory, count; CompoundRecord records[5]; } CompoundPhase;',
         'static const CompoundCase compound_cases[] = {']
for sample in samples:
    c = sample['config']
    effects = ','.join(str(v & 65535) for v in c['effects'])
    changes = ','.join(str(v & 65535) for v in c.get('refreshEffects', [0]*4))
    lines.append('{"%s",%u,%u,%u,%u,%u,%u,%u,%u,{%s},{%s},%u},' % (
        sample['variant'], c.get('item', c.get('skill')), bool(c.get('item')), c['side'], c.get('group', 0),
        c.get('type', 1), c.get('enemies', 1), c['rounds'], bool(c.get('refresh')), effects, changes, bool(c.get('refreshEffects'))))
lines += ['};', 'static const CompoundPhase compound_phases[] = {']
for scenario, sample in enumerate(samples):
    for phase, event in enumerate(sample['events']):
        assert event['mode'] == 3
        rows = []
        for r in event['records']:
            rows.append('{'+','.join(str(r[k]) for k in ['hp','qi','baseAttack','baseDefense','attack','defense','attackTimer','defenseTimer'])+'}')
        lines.append('{%u,%u,%u,%u,{%s}},' % (scenario, phase, event['inventory'], len(rows), ','.join(rows)))
lines += ['};', '#endif', '']
Path('npe-sdl/tests/compound_native.h').write_text('\n'.join(lines), newline='\n')
print(f'{len(samples)} original sequences, {sum(len(e["records"]) for s in samples for e in s["events"])} record phases')
