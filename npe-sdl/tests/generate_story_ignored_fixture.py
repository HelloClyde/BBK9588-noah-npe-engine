import json
from pathlib import Path


def state(s):
    return '{%d,%d,%d,%d,{%s}}' % (
        s['pointer'], s['offset'], s['more'], s['style'], ','.join(map(str, s['rect'])))


report = json.loads(Path('tmp/story-ignored-original/report.json').read_text())
rows = report['cases']
assert report['passed'] and len(rows) == 8
assert {r['more'] for r in rows} == {0, 1, 2, 255}
lines = ['/* Original-only references. Generated by generate_story_ignored_fixture.py. */',
         'typedef struct {uint32_t pointer;uint16_t offset;uint8_t more,style;uint16_t rect[4];} StoryTextState;',
         'typedef struct {const char *name;StoryTextState before,after;unsigned closes;} StoryTextCase;',
         'static const StoryTextCase story_text_cases[]={']
for r in rows:
    assert r['ignoredCommits'] == 0 and r['rawSpaceDelivered']
    lines.append('{"%s",%s,%s,%d},' % (r['name'], state(r['before']), state(r['after']), int(r['closes'])))
lines += ['};']
Path('npe-sdl/tests/story_ignored_native.h').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('8 original story input paths: more0/1/2/255, raw Enter/K ignored and Space delivered')
