import json
from pathlib import Path

def state(s):
    rect=s.get('rect',[0,12,240,131])
    return '{%d,%d,%d,%d,{%s}}'%(s.get('pointer',0),s['offset'],s['more'],s['style'],','.join(map(str,rect)))

lines=['/* Original-only references. Generated by generate_story_text_fixture.py. */',
       'typedef struct {uint32_t pointer;uint16_t offset;uint8_t more,style;uint16_t rect[4];} StoryTextState;',
       'typedef struct {unsigned id,window,count;StoryTextState pages[15];} StoryTextPages;',
       'static const StoryTextPages story_text_pages[]={']
for window,name in enumerate(['native-story-pages.json','native-window-story-pages.json']):
    rows=json.loads((Path('tmp')/name).read_text())
    for r in rows:lines.append('{%d,%d,%d,{%s}},'%(r['id'],window,len(r['pages']),','.join(state(p) for p in r['pages'])))
lines+=['};','typedef struct {const char *name;StoryTextState before,after;unsigned closes;} StoryTextCase;',
        'static const StoryTextCase story_text_cases[]={']
rows=json.loads(Path('tmp/native-story-text-service.json').read_text())
assert len(rows)==11
for r in rows:lines.append('{"%s",%s,%s,%d},'%(r['name'],state(r['before']),state(r['after']),int(r.get('more')==2)))
lines+=['};']
lines+=['typedef struct {unsigned load;StoryTextState before,after;} StoryTextLifetime;',
        'static const StoryTextLifetime story_text_lifetimes[]={']
restart=json.loads(Path('tmp/story-text-restart-native/report.json').read_text())['rows']
loads=json.loads(Path('tmp/story-text-title-boot-native/report.json').read_text())
assert len(restart)==4 and len(loads)==2
for load,group in enumerate([restart,loads]):
    for r in group:lines.append('{%d,%s,%s},'%(load,state(r['before']),state(r['after'])))
lines+=['};']
Path('npe-sdl/tests/story_text_native.h').write_text('\n'.join(lines)+'\n')
print('16 original stories /77 pages and11 live-control cases')
