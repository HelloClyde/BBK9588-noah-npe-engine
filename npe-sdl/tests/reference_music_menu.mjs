import fs from 'node:fs';
import {GameRuntime, initWasm} from '../../tmp/opennoah-headless.mjs';

// Isolated original controller/menu input. The NPE, PRG and saved route are read-only.
const exp=await initWasm({module_or_path:fs.readFileSync(new URL('../../tmp/opennoah_wasm_bg.wasm',import.meta.url))});
const rt=new GameRuntime(fs.readFileSync(new URL('../../tmp/tianjiang-online.opennoah',import.meta.url)),'certified_original_v1');
const cases=[
 {name:'on-same-on',enabled:1,keys:[1,8,4,32,2,2,16]},
 {name:'on-off',enabled:1,keys:[16]},
 {name:'off-on',enabled:0,keys:[2,2,16]},
 {name:'off-same-off',enabled:0,keys:[2,8,4,32,16]},
 {name:'on-cancel',enabled:1,keys:[1,64]},
 {name:'off-cancel',enabled:0,keys:[2,64]},
];
const rows=[];
for(const test of cases){
 rt.restoreBytes(fs.readFileSync(new URL('../../tmp/battle-fresh-start.bin',import.meta.url)));
 const mem=()=>new Uint8Array(exp.memory.buffer),found=[];
 for(let i=0;i+0x8000<mem().length;++i)
  if(mem()[i+0x7934]===3&&mem()[i+0x7935]===0&&mem()[i+0x7936]===1&&mem()[i+0x7a58]===9&&mem()[i+0x7a66]===6)found.push(i);
 if(found.length!==1)throw Error('RAM '+found.length);
 const base=found[0],a=o=>base+o-(o<0x7000?8:0),w=o=>mem()[a(o)-1]*256+mem()[a(o)],b=o=>mem()[a(o)-1];
 const putW=(o,v)=>{mem()[a(o)-1]=v>>>8;mem()[a(o)]=v&255;};
 const tick=mask=>{const out=rt.advance(mask);out.free();},idle=n=>{for(let i=0;i<n;++i)tick(0);};
 const key=mask=>{tick(mask);idle(15);};
 putW(0x7934,1);putW(0x7ab4,1);putW(0x7a50,test.enabled);idle(35);
 for(const mask of [64,2,2,2,16,2,2])key(mask);
 if(w(0x7934)!==6||b(0x7a54)!==5||b(0x7a1e)!==3)throw Error('music parent '+test.name);
 fs.writeFileSync(new URL(`../../tmp/native-music-${test.name}-before.idx`,import.meta.url),rt.framePixelIndices());
 key(16);
 const row={...test,frames:[]};
 const capture=input=>{
  const index=row.frames.length, state={index,input,mode:w(0x7934),menu:b(0x7a54),selection:b(0x7a8a)-1,enabled:w(0x7a50)};
  row.frames.push(state);
  fs.writeFileSync(new URL(`../../tmp/native-music-${test.name}-frame-${index}.idx`,import.meta.url),rt.framePixelIndices());
 };
 capture(0);
 for(const mask of test.keys){key(mask);capture(mask);}
 if(row.frames[0].selection!==test.enabled||row.frames.at(-1).mode!==1)throw Error('music outcome '+JSON.stringify(row));
 rows.push(row);console.log(JSON.stringify(row));
 putW(0x7934,0); // Do not leave a retained battle signature for the next restore.
}
fs.writeFileSync(new URL('../../tmp/native-music-menu.json',import.meta.url),JSON.stringify(rows,null,2)+'\n');
const header='/* Original PRG controller/menu input, generated by reference_music_menu.mjs. */\n'+
 'typedef struct { const char *name; unsigned enabled,count; unsigned keys[8]; unsigned selected[9]; unsigned after_enabled; } MusicMenuCase;\n'+
 'static const MusicMenuCase music_menu_cases[] = {\n'+
 rows.map(r=>`    {"${r.name}",${r.enabled},${r.keys.length},{${r.keys.join(',')}},{${r.frames.map(f=>f.selection).join(',')}},${r.frames.at(-1).enabled}},\n`).join('')+'};\n';
fs.writeFileSync(new URL('music_menu_native.h',import.meta.url),header);
rt.free();
