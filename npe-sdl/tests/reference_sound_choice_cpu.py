import argparse, json, re, struct, sys, time
from pathlib import Path
sys.path.insert(0, str(Path('scripts').resolve()))
from web.np560_web import Emulator, RunJournal

parser = argparse.ArgumentParser(description='Execute original music selection arithmetic')
parser.add_argument('--qemu', type=Path, required=True)
args = parser.parse_args()
out = Path('tmp/sound-choice-cpu'); out.mkdir(exist_ok=True)
prg = Path('tmp/NP560.PRG').read_bytes()
def words(bank, start, end):
    offset = (bank-0x20)*65536+start
    return list(struct.unpack('<%dH' % ((end-start)//2), prg[offset:offset+end-start]))
map_slice = words(0x48, 0x23c4, 0x23ca)
battle_slice = words(0x4d, 0x05b4, 0x05c4)
assert map_slice == [0x0870, 0x4803, 0xc300]
assert battle_slice == [0x0870, 0x68f0, 60, 0xc300, 0x0876, 0x481a, 0xc301, 0x09df]
rows = []
for roll in [0, 9, 10, 19, 20, 29, 30, 39, 40, 49, 50, 59, 60, 61, 32767]:
    code = [0x6800, 2, 0x68ff, 0x6000, 0x68f0, roll] + map_slice + [0x0836, 0x68f0, roll] + battle_slice + [0x0847]
    pc = len(code)*2; code.append(0xc701)
    firmware = out / (str(roll)+'.prg')
    firmware.write_bytes(struct.pack('<%dH' % len(code), *code))
    emu = None
    try:
        emu = Emulator(qemu=args.qemu.resolve(), firmware=firmware.resolve(), start_paused=True,
                       icount_shift=0, journal=RunJournal(out/'runs', case=str(roll)))
        emu.qmp.execute('qom-set', {'path':'/machine','property':'instruction-clock','value':True})
        emu.qmp.execute('cont')
        marker = f'UNSUPPORTED=20:{pc:04x} WORD=c701 COUNT=1'
        for _ in range(300):
            state = emu.qmp.execute('qom-get', {'path':'/machine','property':'cpu-state'})
            if marker in state: break
            time.sleep(.01)
        emu.qmp.execute('stop')
        assert marker in state and 'ROM_MISSING=none' in state and 'INVALID_CONTROL=none' in state, state[:1000]
        regs = {int(k):int(v,16) for k,v in re.findall(r'\bR(\d+)\s*=([0-9a-f]+)', '\n'.join(state.splitlines()[:5]), re.I)}
        row = {'roll':roll,'map_slot':regs[3],'battle_slot':regs[4]}
        assert row['map_slot']==roll%3 and row['battle_slot']==roll%60//10
        rows.append(row); print(json.dumps(row), flush=True)
        (out/(str(roll)+'.cpu.txt')).write_text(state)
    finally:
        if emu: emu.close()
Path('tmp/native-sound-choice-cpu.json').write_text(json.dumps(rows,indent=2)+'\n')
header = ('/* Generated by reference_sound_choice_cpu.py from original PRG instructions. */\n'
          'static const struct { unsigned roll, map_slot, battle_slot; } sound_choice_native[] = {\n')
header += ''.join('    {%d, %d, %d},\n' % (r['roll'], r['map_slot'], r['battle_slot']) for r in rows)
header += '};\n'
Path('npe-sdl/tests/sound_choice_native.h').write_text(header, encoding='utf-8', newline='\n')
