"""Extract NP560 V3.80 resident and extended 12/16-row font assets.

Inputs are the unswapped PRG and unchanged, header-inclusive NAND_IMAGE slot
extracted by scripts/np560_upd.py. No generated/system font is used.
"""
import argparse
import hashlib
from pathlib import Path

ASCII_COUNT = 95
GBK_TRAILS = 191
FONT_BYTES = 8 + (ASCII_COUNT + 126 * GBK_TRAILS) * 24
ASCII12_SOURCE = 0x30F000
PUNCTUATION12_SOURCE = 0x316000
CHINESE12_SOURCE = 0x313960
ASCII16_SOURCE = 0x313800
FONT16_SOURCE = 0x343810
EXTENDED_FIRST_COUNT = 32 * 191
EXTENDED_SECOND_COUNT = 87 * 97
EXTENDED_COUNT = EXTENDED_FIRST_COUNT + EXTENDED_SECOND_COUNT
EXTENDED12_SOURCE = 0x0262BA9C
EXTENDED16_SOURCE = 0x0266B9BA
EXTENDED_END = 0x026DD49A
NAND_SOURCE_DELTA = -0x110000
FONT16_BYTES = 8 + (ASCII_COUNT + 94 * 94 + 33 + EXTENDED_COUNT) * 32
PROGRAM_SHA256 = 'd555609e03ece17f42c1881beeb88361572f18621161de67bc9dc765857089f5'
NAND_SHA256 = '44c3c0332ceab48e95202effc1a6c4f52a07384c4149becf039384ea0c0330ce'


def extended_codes():
    """Native lookup order includes trail-7F slots in both tables."""
    for lead in range(0x81, 0xA1):
        for trail in range(0x40, 0xFF):
            yield lead, trail
    for lead in range(0xA8, 0xFF):
        for trail in range(0x40, 0xA1):
            yield lead, trail


def unpack12(raw: bytes) -> bytes:
    """Original 29:C3C0: paired high nibbles, reverse, extra shift, mask."""
    if len(raw) != 18:
        raise ValueError('packed glyph must contain 18 bytes')
    output = bytearray()
    for row in range(12):
        value = raw[row] | ((raw[12 + row // 2] >> (4 * (row % 2))) & 15) << 8
        reversed_bits = 0
        for _ in range(12):
            reversed_bits = (reversed_bits << 1) | (value & 1)
            value >>= 1
        mask = (reversed_bits << 5) & 0xFFF0
        output.extend(mask.to_bytes(2, 'big'))
    return bytes(output)


def resident_rows(program: bytes, source: int, size: int) -> bytes:
    raw = bytearray(program[source:source + size])
    if len(raw) != size:
        raise ValueError('resident font exceeds PRG')
    raw[0::2], raw[1::2] = raw[1::2], raw[0::2]
    return bytes(raw)


def controls_include(program: bytes) -> str:
    """Original C-font ASCII slots absent from the NPEFONT1 asset layout."""
    if hashlib.sha256(program).hexdigest() != PROGRAM_SHA256:
        raise ValueError('expected the original NP560 V3.80 PRG')
    lines = ['/* Generated by extract_np560_gbk_font.py --controls.',
             '   Original PRG ASCII12_SOURCE + code * 32, first 24 bytes.',
             '   PRG SHA256: ' + PROGRAM_SHA256 + ' */',
             'static const uint8_t native12_controls[33][24] = {']
    for code in list(range(0x20)) + [0x7F]:
        bits = resident_rows(program, ASCII12_SOURCE + code * 32, 24)
        lines.append('    {' + ','.join('0x%02x' % b for b in bits) + '}, /* %02X */' % code)
    return '\n'.join(lines + ['};', ''])


def extract(program: bytes, nand: bytes) -> tuple[bytes, bytes]:
    if hashlib.sha256(program).hexdigest() != PROGRAM_SHA256:
        raise ValueError('expected the original NP560 V3.80 PRG')
    if hashlib.sha256(nand).hexdigest() != NAND_SHA256:
        raise ValueError('expected the unchanged, header-inclusive V3.80 NAND_IMAGE slot')
    blank = resident_rows(program, PUNCTUATION12_SOURCE, 24)
    table = bytearray(b'NPEFONT1' + blank * (ASCII_COUNT + 126 * GBK_TRAILS))

    def put12(lead, trail, bits):
        index = ASCII_COUNT + (lead - 0x81) * GBK_TRAILS + trail - 0x40
        table[8 + index * 24:8 + (index + 1) * 24] = bits

    for code in range(0x20, 0x7F):
        index = code - 0x20
        table[8 + index * 24:8 + (index + 1) * 24] = resident_rows(
            program, ASCII12_SOURCE + code * 32, 24)
    # Native C branches cover the remaining resident slots up to AF / FD.
    for first, end, base in [(0xA1, 0xB0, PUNCTUATION12_SOURCE),
                             (0xB0, 0xFE, CHINESE12_SOURCE)]:
        for lead in range(first, end):
            for trail in range(0xA1, 0xFF):
                index = (lead - 0xA1) * 94 + trail - 0xA1
                put12(lead, trail, resident_rows(program, base + index * 24, 24))
    for index, (lead, trail) in enumerate(extended_codes()):
        source = EXTENDED12_SOURCE + NAND_SOURCE_DELTA + index * 18
        put12(lead, trail, unpack12(nand[source:source + 18]))
    assert len(table) == FONT_BYTES

    font16 = bytearray(b'NPEF16V3')
    for code in range(0x20, 0x7F):
        font16.extend(resident_rows(program, ASCII16_SOURCE + code * 32, 32))
    for index in range(94 * 94):
        font16.extend(resident_rows(program, FONT16_SOURCE + index * 32, 32))
    # Retain V2 ordinary/control offsets; append the original flash table.
    for code in list(range(0x20)) + [0x7F]:
        font16.extend(resident_rows(program, ASCII16_SOURCE + code * 32, 32))
    font16.extend(nand[EXTENDED16_SOURCE + NAND_SOURCE_DELTA:
                       EXTENDED_END + NAND_SOURCE_DELTA])
    assert len(font16) == FONT16_BYTES
    return bytes(table), bytes(font16)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('program', type=Path, help='NP560.PRG V3.80')
    parser.add_argument('nand', type=Path, help='original NP560_NAND_IMAGE.bin slot, including header')
    parser.add_argument('output', type=Path, help='NPEFONT1 12-row table')
    parser.add_argument('output16', type=Path, help='NPEF16V3 16-row table')
    parser.add_argument('--controls', type=Path, help='C include containing the 33 original 12-row ASCII control slots')
    args = parser.parse_args()
    program = args.program.read_bytes()
    tables = extract(program, args.nand.read_bytes())
    for path, data in zip((args.output, args.output16), tables):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(f'{path}: {len(data)} bytes, SHA-256 {hashlib.sha256(data).hexdigest()}')
    if args.controls:
        args.controls.parent.mkdir(parents=True, exist_ok=True)
        args.controls.write_text(controls_include(program), encoding='utf8', newline='\n')
        print(f'{args.controls}: 33 original C-font control glyphs')


if __name__ == '__main__':
    main()
