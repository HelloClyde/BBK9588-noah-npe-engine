"""Extract the three original 8x16 fonts selected by NPC control bytes.

The resident font base and 2F:6BFA descriptors are from NP560 V3.80.
The emitted C data requires no firmware at runtime.
"""
import argparse
import hashlib
import struct
from pathlib import Path

from extract_np560_gbk_font import PROGRAM_SHA256, resident_rows

FONT_TYPES = (8, 9, 23)
DESCRIPTOR_SOURCE = 0x4C6BFA - 0x200000
RESIDENT_BASE = 0x30D000


def extract(program):
    if hashlib.sha256(program).hexdigest() != PROGRAM_SHA256:
        raise ValueError('expected the original NP560 V3.80 PRG')
    fonts = []
    for kind in FONT_TYPES:
        high, low, size, width, height = struct.unpack_from(
            '<5H', program, DESCRIPTOR_SOURCE + kind * 10)
        if (size, width, height) != (16, 8, 16):
            raise ValueError('unexpected NPC font descriptor')
        start = RESIDENT_BASE + (high << 16) + low
        fonts.append(resident_rows(program, start, 256 * size))
    return fonts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('program', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    fonts = extract(args.program.read_bytes())
    lines = ['/* Original NP560 V3.80 fonts 8, 9, 23; generated by',
             '   tools/extract_np560_npc_fonts.py. One byte per 8x16 row. */',
             'static const uint8_t native_npc_fonts[3][256][16] = {']
    for kind, data in zip(FONT_TYPES, fonts):
        lines.append('    { /* font %d */' % kind)
        for code in range(256):
            row = data[code * 16:(code + 1) * 16]
            lines.append('        {' + ','.join('0x%02x' % v for v in row) + '},')
        lines.append('    },')
    lines.append('};')
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('%s: 768 original glyphs, data SHA-256 %s' % (
        args.output, hashlib.sha256(b''.join(fonts)).hexdigest()))


if __name__ == '__main__':
    main()
