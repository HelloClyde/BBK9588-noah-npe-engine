#!/usr/bin/env python3
"""Regenerate C lookup constants from the independently modeled codec tables.

This is a build-time maintenance tool. The NPE runtime never invokes Python.
"""

from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

from np560_mobivoice_codebook_data import CODEBOOKS  # noqa: E402
from np560_mobivoice_tables import (  # noqa: E402
    INTERPOLATION_TAPS, LSF_BIAS, LSF_COSINE_TABLE, LSF_PREDICTOR_GAIN,
    PITCH_GAINS, PULSE_AMPLITUDES, PULSE_POSITIONS,
)


def array(name: str, values: tuple[int, ...], columns: int = 12) -> str:
    rows = [f"static const int16_t {name}[{len(values)}] = {{"]
    for start in range(0, len(values), columns):
        rows.append("    " + ", ".join(map(str, values[start:start + columns])) + ",")
    rows.append("};")
    return "\n".join(rows)


def main() -> None:
    arrays = (
        ("codebook0", CODEBOOKS[0]),
        ("codebook1", CODEBOOKS[1]),
        ("codebook2", CODEBOOKS[2]),
        ("interpolation_taps", INTERPOLATION_TAPS),
        ("pulse_positions", PULSE_POSITIONS),
        ("pulse_amplitudes", PULSE_AMPLITUDES),
        ("pitch_gains", PITCH_GAINS),
        ("lsf_bias", LSF_BIAS),
        ("lsf_predictor_gain", LSF_PREDICTOR_GAIN),
        ("lsf_cosine_table", LSF_COSINE_TABLE),
    )
    output = ROOT / "npe-sdl" / "audio_tables.inc"
    output.write_text(
        "/* Generated by tools/generate_audio_tables.py from independent "
        "candidate tables. */\n" +
        "\n\n".join(array(name, tuple(values)) for name, values in arrays) + "\n",
        encoding="ascii",
    )
    print(output)


if __name__ == "__main__":
    main()
