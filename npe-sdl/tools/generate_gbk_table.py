"""Regenerate the C11 GBK lookup table from Python's standard GBK codec.

The generated table is compiled into npe-sdl; Python is not a runtime dependency.
"""

from pathlib import Path


def main() -> None:
    values = []
    for lead in range(0x81, 0xFF):
        for trail in range(0x40, 0xFF):
            if trail == 0x7F:
                continue
            try:
                value = ord(bytes((lead, trail)).decode("gbk"))
            except UnicodeDecodeError:
                value = 0
            if value > 0xFFFF:
                raise ValueError("GBK table contains a non-BMP code point")
            values.append(value)
    if len(values) != 126 * 190:
        raise AssertionError("unexpected GBK table size")
    rows = [
        "    " + ", ".join(f"0x{value:04x}" for value in values[i:i + 12]) + ","
        for i in range(0, len(values), 12)
    ]
    output = Path(__file__).resolve().parents[1] / "gbk_table.inc"
    output.write_text(
        "/* Generated by tools/generate_gbk_table.py. */\n"
        "static const uint16_t gbk_unicode[126 * 190] = {\n"
        + "\n".join(rows) + "\n};\n",
        encoding="ascii",
    )
    print(output)


if __name__ == "__main__":
    main()
